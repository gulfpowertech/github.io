  function resolve(lang, key) {
    var parts = key.split(".");
    var node = dict[lang];
    for (var i = 0; i < parts.length; i++) {
      if (!node) return null;
      node = node[parts[i]];
    }
    return typeof node === "string" ? node : null;
  }

  // Rewrites internal page links (index.html, services.html, ...) so the
  // chosen language survives full-page navigation even when localStorage
  // is unavailable (e.g. pages opened directly via file://).
  function propagateLangToLinks(lang) {
    var links = document.querySelectorAll("a[href]");
    links.forEach(function (a) {
      var href = a.getAttribute("href");
      if (!href) return;
      if (href.indexOf(".html") === -1) return;
      if (/^([a-z]+:)?\/\//i.test(href) || /^(mailto|tel):/i.test(href)) return;

      var hashIndex = href.indexOf("#");
      var base = hashIndex >= 0 ? href.slice(0, hashIndex) : href;
      var hash = hashIndex >= 0 ? href.slice(hashIndex) : "";
      var qIndex = base.indexOf("?");
      var path = qIndex >= 0 ? base.slice(0, qIndex) : base;

      a.setAttribute("href", path + "?lang=" + lang + hash);
    });
  }

  function updateUrlState(lang) {
    try {
      var url = new URL(window.location.href);
      url.searchParams.set("lang", lang);
      window.history.replaceState(null, "", url.toString());
    } catch (e) {}
  }

  function applyLanguage(lang, options) {
    if (lang !== "ar" && lang !== "en") lang = "en";
    var silent = options && options.silent;

    document.documentElement.setAttribute("lang", lang === "ar" ? "ar" : "en");
    document.documentElement.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");

    var textEls = document.querySelectorAll("[data-i18n]");
    textEls.forEach(function (el) {
      var val = resolve(lang, el.getAttribute("data-i18n"));
      if (val !== null) el.textContent = val;
    });

    var htmlEls = document.querySelectorAll("[data-i18n-html]");
    htmlEls.forEach(function (el) {
      var val = resolve(lang, el.getAttribute("data-i18n-html"));
      if (val !== null) el.innerHTML = val;
    });

    var phEls = document.querySelectorAll("[data-i18n-placeholder]");
    phEls.forEach(function (el) {
      var val = resolve(lang, el.getAttribute("data-i18n-placeholder"));
      if (val !== null) el.setAttribute("placeholder", val);
    });

    var btn = document.getElementById("lang-toggle-btn");
    if (btn) btn.textContent = lang === "ar" ? "English" : "العربية";

    propagateLangToLinks(lang);
    if (!silent) updateUrlState(lang);
    try { localStorage.setItem(LANG_KEY, lang); } catch (e) {}
  }

  function toggleLanguage() {
    var current = document.documentElement.getAttribute("lang") === "ar" ? "ar" : "en";
    applyLanguage(current === "ar" ? "en" : "ar");
  }

  window.toggleLanguage = toggleLanguage;
  window.applyLanguage = applyLanguage;
  window.i18nText = function (key) {
    var lang = document.documentElement.getAttribute("lang") === "ar" ? "ar" : "en";
    return resolve(lang, key) || resolve("en", key) || key;
  };

  function getInitialLang() {
    try {
      var urlLang = new URLSearchParams(window.location.search).get("lang");
      if (urlLang === "ar" || urlLang === "en") return urlLang;
    } catch (e) {}
    try {
      var saved = localStorage.getItem(LANG_KEY);
      if (saved === "ar" || saved === "en") return saved;
    } catch (e) {}
    return "en";
  }

  document.addEventListener("DOMContentLoaded", function () {
    // silent: an initial load shouldn't push a redundant history entry —
    // the URL already carries ?lang= (or is about to via link rewriting).
    applyLanguage(getInitialLang(), { silent: true });
  });
